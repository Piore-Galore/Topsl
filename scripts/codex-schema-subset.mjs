#!/usr/bin/env node
// Copies the parts of Codex's generated app-server schema that Topsl's tests
// check its messages against, with every definition they reference.
//
//   codex app-server generate-json-schema --experimental --out <dir>
//   node scripts/codex-schema-subset.mjs <dir>/codex_app_server_protocol.schemas.json <version>
//
// Nested names such as `v2/ThreadStartParams` become flat definition keys, and
// references use JSON Pointer escaping (`#/definitions/v2~1ThreadStartParams`),
// so the result is one self-contained draft-07 document.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const roots = [
  "InitializeParams",
  "v2/ThreadStartParams",
  "v2/TurnStartParams",
  "DynamicToolCallParams",
  "DynamicToolCallResponse",
  "v2/ItemCompletedNotification",
  "v2/ItemStartedNotification",
  "CommandExecutionRequestApprovalParams",
  "CommandExecutionRequestApprovalResponse",
  "FileChangeRequestApprovalParams",
  "FileChangeRequestApprovalResponse",
];
const [input, version] = process.argv.slice(2);
if (!input || !/^\d+\.\d+\.\d+$/.test(version ?? ""))
  throw new Error(
    "Usage: node scripts/codex-schema-subset.mjs <codex_app_server_protocol.schemas.json> <codex version>",
  );
const bundle = JSON.parse(readFileSync(input, "utf8"));
const prefix = "#/definitions/";
const find = (name) => {
  const node = name
    .split("/")
    .reduce((parent, key) => parent?.[key], bundle.definitions);
  if (!node || typeof node !== "object")
    throw new Error(`The schema has no definition ${name}.`);
  return node;
};
const definitions = {};
const copy = (name) => {
  if (definitions[name]) return;
  definitions[name] = {};
  const { $schema, ...node } = find(name);
  definitions[name] = JSON.parse(JSON.stringify(node), (key, value) => {
    if (key !== "$ref" || typeof value !== "string") return value;
    if (!value.startsWith(prefix))
      throw new Error(`Unexpected reference ${value} in ${name}.`);
    const target = value.slice(prefix.length);
    copy(target);
    return prefix + target.replaceAll("~", "~0").replaceAll("/", "~1");
  });
};
for (const root of roots) copy(root);
const sorted = Object.fromEntries(
  Object.keys(definitions)
    .sort()
    .map((name) => [name, definitions[name]]),
);
const output = path.resolve(
  `tests/fixtures/codex-app-server-${version}.schema.json`,
);
writeFileSync(
  output,
  JSON.stringify(
    {
      $schema: "http://json-schema.org/draft-07/schema#",
      $comment: `Generated by \`codex app-server generate-json-schema --experimental\` from Codex CLI ${version}, then reduced by scripts/codex-schema-subset.mjs to ${roots.join(", ")} and the definitions they reference.`,
      definitions: sorted,
    },
    null,
    2,
  ) + "\n",
);
console.log(`${Object.keys(sorted).length} definitions written to ${output}`);

import os from "node:os";
import path from "node:path";
import { constants } from "node:fs";
import { lstat, open, readdir, realpath } from "node:fs/promises";
import { hash } from "../domain/invariants";
import type { ClaudeTranscriptSource } from "../domain/claude-steps";
import { isWithin, nativeEnvironment } from "../platform/system";

/**
 * The record shapes Topsl recognizes in a Claude Code session transcript, as
 * the fixtures in tests/claude-transcripts.test.ts cover them. Claude Code
 * describes the format as internal and changes it between versions, so Topsl
 * pins these shapes rather than a version, and anything else falls back to
 * the owner's paste. They are inferred from Topsl's history reader and its
 * fixtures, not yet from a real Claude Code transcript.
 */
export const claudeTranscriptShapes = "claude-code-session-v1";
/** The bound the history reader applies to a transcript. */
export const maxTranscriptBytes = 30_000_000;
/** The longest reply a hand-back takes, as for a pasted reply. */
const maxReplyLength = 1_000_000;
const sessionPattern =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
/** Flags Topsl knows the meaning of. Another `is…` flag that is set could
 * change what its record means, so it makes the record unrecognized. */
const knownFlags = new Set([
  "isSidechain",
  "isMeta",
  "isCompactSummary",
  "isVisibleInTranscriptOnly",
  "isApiErrorMessage",
  "isSnapshotUpdate",
]);
const parts = {
  user: new Set(["text", "tool_result", "image", "document"]),
  assistant: new Set(["text", "tool_use", "thinking", "redacted_thinking"]),
};
/** Records that carry no conversation. They need not name the session or
 * folder, but must not name another. All but `summary` were first seen in
 * Claude Code 2.1.300's transcripts of two live runs on 18 October 2026,
 * by their type and field names only. */
const metadataTypes = new Set([
  "summary",
  "file-history-snapshot",
  "file-history-delta",
  "mode",
  "permission-mode",
  "ai-title",
  "last-prompt",
  "atis-latch",
  "cost-state",
  "api-request",
  "api-request-blob",
  "api-request-shape",
]);
/** What Claude Code attaches to a turn as context, as in those live runs.
 * None is a prompt; another kind, such as a message typed while Claude
 * works, might be, so it makes the transcript unrecognized. Attachments
 * must name the session and the step's folder, as conversation records do.
 * The `plan_mode` kinds are Claude Code 2.1.302's Plan-mode reminders:
 * `plan_mode` was in a live review session's transcript on 20 October 2026
 * (D-27); `plan_mode_reentry` and `plan_mode_exit` are the reminders the
 * same version's executable writes on re-entering and leaving Plan mode,
 * found there by name only. `plan_file_reference`, which carries a plan
 * file's text, stays unrecognized. */
const attachmentKinds = new Set([
  "agent_listing_delta",
  "credential_org",
  "date",
  "deferred_tools_delta",
  "deferred_tools_record",
  "environment",
  "mcp_instructions_delta",
  "model",
  "plan_mode",
  "plan_mode_exit",
  "plan_mode_reentry",
  "prompt_snapshot",
  "remote_session_change",
  "session_context",
  "skill_listing",
  "total_tokens_reminder",
]);
/** What Claude Code records for a local command such as /exit, which is not a prompt. */
const localCommand =
  /^(?:<(?:command-name|command-message|command-args|local-command-stdout|local-command-stderr|local-command-caveat|bash-input|bash-stdout|bash-stderr)>|Caveat: The messages below were generated by the user while running local commands)/;
const interruption = /^\[Request interrupted by user(?: for tool use)?\]$/;

type JsonObject = Record<string, unknown>;
const object = (value: unknown): value is JsonObject =>
  !!value && typeof value === "object" && !Array.isArray(value);
interface Line {
  line: number;
  value: JsonObject;
}

export type ClaudeTranscriptRead =
  | { ok: true; text: string; source: ClaudeTranscriptSource }
  | { ok: false; reason: string };

/** Claude Code's configuration folder, where the Claude Code Topsl opens keeps its transcripts. */
export function claudeConfigDirectory(): string {
  return (
    nativeEnvironment().CLAUDE_CONFIG_DIR ?? path.join(os.homedir(), ".claude")
  );
}

/**
 * Claude's final reply in the session Topsl opened for a workflow's step, read
 * from `<config>/projects/<folder>/<session id>.jsonl` and from nothing else.
 * Every conversation record must name that session and the step's folder or a
 * folder inside it, and every record must have a shape Topsl recognizes. The reply is the text of
 * Claude's last message after the owner's last prompt, which must end the
 * turn: no tool call, interruption or API error. When Claude Code wrote
 * another session in the same folder after Topsl opened this one, as after
 * /clear or /branch, the reply may be there instead, so Topsl takes none.
 * Anything else returns the reason, and the owner pastes the reply instead.
 */
export async function readClaudeStepReply(input: {
  configDirectory: string;
  sessionId: string;
  /** The project folder for a build or repair, or the review's copy. */
  folder: string;
  /** When Topsl asked to open Claude Code for this session. */
  openedAt: string;
}): Promise<ClaudeTranscriptRead> {
  const fail = (reason: string): ClaudeTranscriptRead => ({
    ok: false,
    reason,
  });
  if (!sessionPattern.test(input.sessionId))
    return fail("The step's session id is not one Topsl generated.");
  const projects = path.join(input.configDirectory, "projects"),
    name = `${input.sessionId}.jsonl`;
  const found: string[] = [];
  try {
    const root = await realpath(projects);
    for (const entry of await readdir(root, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const file = path.join(root, entry.name, name);
      if (await lstat(file).catch(() => null)) found.push(file);
    }
  } catch {
    return fail(
      `Claude Code has no projects folder Topsl can read at ${projects}.`,
    );
  }
  if (!found.length)
    return fail(
      `Claude Code has no transcript for session ${input.sessionId} in ${projects}.`,
    );
  if (found.length > 1)
    return fail(
      `More than one of Claude Code's project folders has a transcript for session ${input.sessionId}.`,
    );
  const file = found[0];

  let bytes: Buffer;
  try {
    const handle = await open(file, constants.O_RDONLY | constants.O_NOFOLLOW);
    try {
      const before = await handle.stat();
      if (!before.isFile())
        return fail("The session's transcript is not a regular file.");
      if (before.size > maxTranscriptBytes)
        return fail(
          `The session's transcript is larger than the ${maxTranscriptBytes / 1_000_000} MB Topsl reads.`,
        );
      bytes = Buffer.alloc(before.size);
      let count = 0;
      while (count < bytes.length) {
        const { bytesRead } = await handle.read(
          bytes,
          count,
          bytes.length - count,
          count,
        );
        if (!bytesRead) break;
        count += bytesRead;
      }
      const after = await handle.stat();
      if (
        count !== before.size ||
        after.size !== before.size ||
        after.mtimeMs !== before.mtimeMs
      )
        return fail(
          "The session's transcript changed while Topsl read it. Hand the reply back again once Claude Code has stopped.",
        );
    } finally {
      await handle.close();
    }
  } catch {
    return fail(
      "Topsl could not open the session's transcript as a regular file.",
    );
  }

  // After /clear or /branch, Claude Code goes on in a new session in the same folder.
  const opened = Date.parse(input.openedAt),
    directory = path.dirname(file);
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === name || !entry.name.endsWith(".jsonl")) continue;
    const other = await lstat(path.join(directory, entry.name)).catch(
      () => null,
    );
    if (other && other.mtimeMs >= opened)
      return fail(
        "Claude Code also wrote another session's transcript for this folder while the step was open, as it does after /clear or /branch, so Topsl cannot tell which session has the step's reply.",
      );
  }

  let text: string;
  try {
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    return fail("The session's transcript is not valid UTF-8.");
  }
  if (!text.endsWith("\n"))
    return fail(
      text
        ? "The session's transcript ends in the middle of a record."
        : "The session's transcript is empty.",
    );
  const lines: Line[] = [];
  for (const [index, raw] of text.slice(0, -1).split("\n").entries()) {
    const line = raw.replace(/\r$/, "");
    if (!line.trim()) continue;
    let value: unknown;
    try {
      value = JSON.parse(line);
    } catch {
      return fail(`Line ${index + 1} of the transcript is not a JSON record.`);
    }
    if (!object(value))
      return fail(`Line ${index + 1} of the transcript is not a JSON object.`);
    lines.push({ line: index + 1, value });
  }

  let folder: string;
  try {
    folder = await realpath(input.folder);
  } catch {
    return fail(
      "The step's folder is gone, so Topsl cannot check the transcript's folder.",
    );
  }
  const folders = new Map<string, string | null>();
  // Claude Code records the folder it is in, which follows a `cd` into a subfolder.
  const inFolder = async (cwd: unknown) => {
    if (typeof cwd !== "string" || !path.isAbsolute(cwd)) return false;
    if (!folders.has(cwd))
      folders.set(cwd, await realpath(cwd).catch(() => null));
    const real = folders.get(cwd);
    return !!real && isWithin(folder, real);
  };
  for (const { line, value } of lines) {
    const where = `Line ${line} of the transcript`,
      type = value.type;
    if (typeof type !== "string") return fail(`${where} has no record type.`);
    for (const [key, flag] of Object.entries(value))
      if (/^is[A-Z]/.test(key) && flag === true && !knownFlags.has(key))
        return fail(
          `${where} sets ${key.slice(0, 80)}, a flag Topsl does not recognize.`,
        );
    if (metadataTypes.has(type)) {
      if (value.sessionId !== undefined && value.sessionId !== input.sessionId)
        return fail(`${where} names another session.`);
      if (value.cwd !== undefined && !(await inFolder(value.cwd)))
        return fail(`${where} names a folder outside the step's.`);
      continue;
    }
    if (
      type !== "user" &&
      type !== "assistant" &&
      type !== "system" &&
      type !== "attachment"
    )
      return fail(
        `${where} has the record type ${JSON.stringify(type.slice(0, 80))}, which Topsl does not recognize.`,
      );
    if (value.sessionId !== input.sessionId)
      return fail(
        `${where} ${value.sessionId === undefined ? "names no session" : "names another session"}.`,
      );
    if (!(await inFolder(value.cwd)))
      return fail(
        `${where} ${value.cwd === undefined ? "names no folder" : "names a folder outside the step's"}.`,
      );
    if (type === "system") continue;
    if (type === "attachment") {
      const kind = object(value.attachment) ? value.attachment.type : undefined;
      if (typeof kind !== "string" || !attachmentKinds.has(kind))
        return fail(
          typeof kind === "string"
            ? `${where} has an attachment of kind ${JSON.stringify(kind.slice(0, 80))}, which Topsl does not recognize.`
            : `${where} has an attachment Topsl does not recognize.`,
        );
      continue;
    }
    if (typeof value.uuid !== "string" || !value.uuid)
      return fail(`${where} has no record id.`);
    const message = value.message;
    if (!object(message) || message.role !== type)
      return fail(`${where} has no ${type} message.`);
    if (type === "user" && typeof message.content === "string") continue;
    if (!Array.isArray(message.content))
      return fail(`${where} has message content Topsl does not recognize.`);
    for (const part of message.content)
      if (
        !object(part) ||
        !parts[type].has(String(part.type)) ||
        (part.type === "text" && typeof part.text !== "string")
      )
        return fail(
          object(part)
            ? `${where} has a message part of type ${JSON.stringify(String(part.type).slice(0, 80))}, which Topsl does not recognize.`
            : `${where} has a message part Topsl does not recognize.`,
        );
  }

  // The conversation, without a subagent's side chain.
  const chain = lines.filter(
    ({ value }) =>
      (value.type === "user" || value.type === "assistant") &&
      value.isSidechain !== true,
  );
  const content = (value: JsonObject) =>
      (value.message as JsonObject).content as string | JsonObject[],
    textOf = (value: JsonObject) => {
      const c = content(value);
      return typeof c === "string"
        ? c
        : c
            .filter((part) => part.type === "text")
            .map((part) => part.text as string)
            .join("\n");
    },
    toolResult = (value: JsonObject) => {
      const c = content(value);
      return (
        value.toolUseResult !== undefined ||
        (typeof c !== "string" && c.some((part) => part.type === "tool_result"))
      );
    },
    prompt = (value: JsonObject) => {
      if (
        value.type !== "user" ||
        value.isMeta === true ||
        value.isCompactSummary === true ||
        toolResult(value)
      )
        return false;
      const t = textOf(value).trim();
      return !!t && !localCommand.test(t) && !interruption.test(t);
    };
  const last = chain.findLastIndex(({ value }) => prompt(value));
  if (last < 0) return fail("The session has no prompt from you.");
  const after = chain.slice(last + 1),
    end = after.findLastIndex(({ value }) => value.type === "assistant");
  if (end < 0)
    return fail("Claude has no reply after your last prompt in this session.");
  // Claude Code records one message's parts as consecutive records with its id.
  const id = (after[end].value.message as JsonObject).id;
  let start = end;
  while (
    typeof id === "string" &&
    start > 0 &&
    after[start - 1].value.type === "assistant" &&
    (after[start - 1].value.message as JsonObject).id === id
  )
    start--;
  const reply = after.slice(start, end + 1);
  if (reply.some(({ value }) => value.isApiErrorMessage === true))
    return fail(
      "Claude Code's last message in this session is an API error, not Claude's reply.",
    );
  if (
    reply.some(({ value }) =>
      (content(value) as JsonObject[]).some((part) => part.type === "tool_use"),
    )
  )
    return fail(
      "Claude's last turn in this session ended in a tool call, so Claude Code may have exited before Claude finished.",
    );
  for (const { value } of after.slice(end + 1)) {
    if (toolResult(value))
      return fail("Claude's last turn in this session did not finish.");
    if (interruption.test(textOf(value).trim()))
      return fail("Claude's last reply in this session was interrupted.");
  }
  const answer = reply
    .map(({ value }) => textOf(value))
    .filter(Boolean)
    .join("\n")
    .trim();
  if (!answer)
    return fail("Claude's last message in this session has no text.");
  if (answer.length > maxReplyLength)
    return fail(
      "Claude's last reply is longer than the 1,000,000 characters Topsl takes.",
    );
  return {
    ok: true,
    text: answer,
    source: {
      shapes: claudeTranscriptShapes,
      sessionId: input.sessionId,
      file,
      bytes: bytes.length,
      sha256: hash(bytes),
      records: lines.length,
      replyRecord: reply.at(-1)!.value.uuid as string,
    },
  };
}

// Generated by Codex CLI 0.163.0; see scripts/codex-schema-subset.mjs.
const codexSchema = JSON.parse(
  readFileSync(
    path.resolve("tests/fixtures/codex-app-server-0.163.0.schema.json"),
    "utf8",
  ),
);
function codexAccepts(definition: string, value: unknown) {
  const result = z
    .fromJSONSchema({
      ...codexSchema,
      $ref: `#/definitions/${definition.replaceAll("/", "~1")}`,
    })
    .safeParse(value);
  return result.success
    ? true
    : `${definition}: ${JSON.stringify(result.error.issues)}`;
}

const fixtures: Array<
  Awaited<ReturnType<typeof fixture>> & { runtime: RuntimeManager }
> = [];
afterEach(async () => {
  for (const f of fixtures.splice(0)) {
    await f.runtime.close();
    f.store.close();
    await rm(f.directory, { recursive: true, force: true });
  }
});

async function setup() {
  const f = await fixture(),
    log = path.join(f.directory, "frames.jsonl");
  const runtime = new RuntimeManager(
    f.store,
    () => {},
    () => {},
    (_executable, cwd) =>
      new RpcPeer(
        process.execPath,
        [path.resolve("tests/fixtures/codex.cjs")],
        cwd,
        { ...nativeEnvironment(), ELECTRON_RUN_AS_NODE: "1", FIXTURE_LOG: log },
      ),
  );
  fixtures.push({ ...f, runtime });
  const project = {
    id: "p",
    name: "fixture",
    path: f.directory,
    realPath: f.directory,
    trusted: true,
    createdAt: now(),
  };
  f.store.put("project", project);
  const repository = runtime.coordinator.repository;
  let conversations = 0;
  /** Starts one run for a new attempt, as the workflow's driver does. */
  const start = (
    prompt: string,
    mode: "review" | "edit",
    options: { tools?: ToolBinding; freshSession?: boolean } = {},
  ) => {
    const workspace = repository.ensureWorkspace(project),
      created = repository.createTask({
        projectId: project.id,
        workspaceId: workspace.id,
        title: "Fixture task",
        role: mode === "review" ? "reviewer" : "implementer",
      }),
      task = repository.transitionTask(created.id, created.revision, "ready"),
      attempt = repository.prepareAttempt({
        taskId: task.id,
        expectedRevision: task.revision,
        provider: "codex",
        requestedModel: "fixture-model",
        freshSession: true,
      }),
      conversation = {
        id: `c${++conversations}`,
        projectId: project.id,
        title: "Fixture chat",
        nativeSessions: {},
        createdAt: now(),
      };
    f.store.put("conversation", conversation);
    return runtime.start(
      f.installation,
      conversation,
      project,
      prompt,
      "fixture-model",
      mode,
      {
        attemptId: attempt.id,
        freshSession: options.freshSession ?? true,
        ...(options.tools ? { tools: options.tools } : {}),
      },
    );
  };
  const finished = async (run: Run) => {
    await vi.waitFor(() =>
      expect(f.store.get<Run>("run", run.id)?.status).toBe("completed"),
    );
    // The workspace stays leased until Topsl confirms the process exited,
    // which can take seconds on Windows. The next run needs it free.
    await vi.waitFor(() => expect(runtime.hasActive()).toBe(false), {
      timeout: 30_000,
    });
    return f.store
      .list<Message>("message")
      .filter((message) => message.runId === run.id);
  };
  const frames = () =>
    readFileSync(log, "utf8")
      .trim()
      .split("\n")
      .map((line) => JSON.parse(line) as { from: string; frame: any });
  const toolEvents = () =>
    (
      f.store.db
        .prepare("SELECT body FROM events WHERE kind = 'run.tool-call'")
        .all() as Array<{ body: string }>
    ).map((row) => JSON.parse(row.body));
  return { ...f, runtime, start, finished, frames, toolEvents };
}

function echoTools() {
  const calls: ProviderToolCall[] = [];
  const tools: ToolBinding = {
    toolset: {
      namespace: "topsl_fixture",
      description: "Fixture tools answered by Topsl.",
      tools: [
        {
          name: "echo",
          description: "Returns its text.",
          inputSchema: {
            type: "object",
            properties: { text: { type: "string" } },
            required: ["text"],
            additionalProperties: false,
          },
        },
      ],
    },
    async call(call): Promise<ProviderToolResult> {
      calls.push(call);
      return {
        text: `echo: ${(call.arguments as { text: string }).text}`,
        success: true,
      };
    },
  };
  return { tools, calls };
}
const callEcho = (overrides: Record<string, unknown> = {}) =>
  `tool ${JSON.stringify({ namespace: "topsl_fixture", tool: "echo", arguments: { text: "hello" }, ...overrides })}`;

describe("Codex tool channel", () => {
  test("only a fresh review session declares Topsl's tools", async () => {
    const f = await setup(),
      { tools } = echoTools();
    await f.finished(await f.start("hello", "review", { tools }));
    await f.finished(await f.start("hello", "edit"));
    const starts = f
      .frames()
      .filter((entry) => entry.frame.method === "thread/start");
    expect(starts).toHaveLength(2);
    expect(starts[0].frame.params.dynamicTools).toEqual([
      {
        type: "namespace",
        name: "topsl_fixture",
        description: "Fixture tools answered by Topsl.",
        tools: [
          {
            type: "function",
            name: "echo",
            description: "Returns its text.",
            inputSchema: tools.toolset.tools[0].inputSchema,
          },
        ],
      },
    ]);
    expect(starts[1].frame.params).not.toHaveProperty("dynamicTools");
    const before = f.frames().length;
    await expect(f.start("hello", "edit", { tools })).rejects.toThrow(
      "fresh review session",
    );
    await expect(
      f.start("hello", "review", { tools, freshSession: false }),
    ).rejects.toThrow("fresh review session");
    // Neither refusal started a runtime or recorded a run for its attempt.
    expect(f.frames()).toHaveLength(before);
    expect(f.store.list<Run>("run")).toHaveLength(2);
  });

  test("a call from the session's own turn is answered by the attempt's handler", async () => {
    const f = await setup(),
      { tools, calls } = echoTools();
    const run = await f.start(callEcho(), "review", { tools }),
      messages = await f.finished(run);
    expect(calls).toEqual([
      {
        threadId: "thread-fixture",
        turnId: "turn-fixture",
        callId: "call-fixture",
        namespace: "topsl_fixture",
        tool: "echo",
        arguments: { text: "hello" },
      },
    ]);
    const response = f
      .frames()
      .find(
        (entry) => entry.from === "topsl" && entry.frame.id === "tool-fixture",
      )!.frame;
    expect(response.result).toEqual({
      contentItems: [{ type: "inputText", text: "echo: hello" }],
      success: true,
    });
    expect(
      messages.find((message) => message.nativeId === "tool-item-fixture"),
    ).toMatchObject({ role: "tool" });
    expect(f.toolEvents()).toEqual([
      {
        runId: run.id,
        callId: "call-fixture",
        namespace: "topsl_fixture",
        tool: "echo",
        outcome: "answered",
        detail: null,
      },
    ]);
  });

  test("calls from another thread or turn, or for an undeclared tool, are refused without running the handler", async () => {
    const f = await setup(),
      { tools, calls } = echoTools();
    for (const overrides of [
      { threadId: "another-thread" },
      { turnId: "another-turn" },
      { tool: "read_anything" },
      { namespace: "another_namespace" },
    ])
      await f.finished(await f.start(callEcho(overrides), "review", { tools }));
    expect(calls).toHaveLength(0);
    const responses = f
      .frames()
      .filter(
        (entry) => entry.from === "topsl" && entry.frame.id === "tool-fixture",
      )
      .map((entry) => entry.frame.result);
    expect(responses).toEqual([
      {
        contentItems: [
          {
            type: "inputText",
            text: "This tool call is outside the active turn.",
          },
        ],
        success: false,
      },
      {
        contentItems: [
          {
            type: "inputText",
            text: "This tool call is outside the active turn.",
          },
        ],
        success: false,
      },
      {
        contentItems: [{ type: "inputText", text: "Topsl has no such tool." }],
        success: false,
      },
      {
        contentItems: [{ type: "inputText", text: "Topsl has no such tool." }],
        success: false,
      },
    ]);
    expect(f.toolEvents().map((event) => event.outcome)).toEqual([
      "refused",
      "refused",
      "refused",
      "refused",
    ]);
  });

  test("a session without tools refuses calls, and a failing handler reports its error", async () => {
    const f = await setup(),
      failing: ToolBinding = {
        toolset: echoTools().tools.toolset,
        call: async () => {
          throw new Error("The fixture reader is unavailable.");
        },
      };
    await f.finished(await f.start(callEcho(), "edit"));
    await f.finished(await f.start(callEcho(), "review"));
    await f.finished(await f.start(callEcho(), "review", { tools: failing }));
    const responses = f
      .frames()
      .filter(
        (entry) => entry.from === "topsl" && entry.frame.id === "tool-fixture",
      )
      .map((entry) => entry.frame.result);
    expect(responses.map((result) => result.success)).toEqual([
      false,
      false,
      false,
    ]);
    expect(responses.map((result) => result.contentItems[0].text)).toEqual([
      "No Topsl tools are installed for this session.",
      "No Topsl tools are installed for this session.",
      "The fixture reader is unavailable.",
    ]);
    expect(f.toolEvents().map((event) => event.outcome)).toEqual([
      "refused",
      "refused",
      "failed",
    ]);
    expect(f.toolEvents().map((event) => event.detail)).toEqual([
      "No Topsl tools are installed for this session.",
      "No Topsl tools are installed for this session.",
      "The fixture reader is unavailable.",
    ]);
  });

  test("messages match the schema Codex 0.163.0 generates", async () => {
    const f = await setup(),
      { tools } = echoTools();
    await f.finished(await f.start(callEcho(), "review", { tools }));
    await f.finished(await f.start("hello", "edit"));
    const frames = f.frames(),
      sent = (method: string) =>
        frames.filter(
          (entry) => entry.from === "topsl" && entry.frame.method === method,
        );
    expect(sent("initialize")).toHaveLength(2);
    for (const { frame } of sent("initialize")) {
      expect(frame.params.capabilities).toEqual({ experimentalApi: true });
      expect(codexAccepts("InitializeParams", frame.params)).toBe(true);
    }
    for (const { frame } of sent("thread/start"))
      expect(codexAccepts("v2/ThreadStartParams", frame.params)).toBe(true);
    for (const { frame } of sent("turn/start"))
      expect(codexAccepts("v2/TurnStartParams", frame.params)).toBe(true);
    const response = frames.find(
      (entry) => entry.from === "topsl" && entry.frame.id === "tool-fixture",
    )!.frame;
    expect(codexAccepts("DynamicToolCallResponse", response.result)).toBe(true);
    // The stand-in's own frames follow the schema too, so these tests do not
    // pass against a protocol Codex does not speak.
    const call = frames.find(
      (entry) => entry.frame.method === "item/tool/call",
    )!.frame;
    expect(codexAccepts("DynamicToolCallParams", call.params)).toBe(true);
    const item = frames.find(
      (entry) =>
        entry.frame.method === "item/completed" &&
        entry.frame.params.item.type === "dynamicToolCall",
    )!.frame;
    expect(codexAccepts("v2/ItemCompletedNotification", item.params)).toBe(
      true,
    );
    // The check rejects what Codex would not accept.
    expect(
      codexAccepts("DynamicToolCallResponse", {
        contentItems: [{ type: "text", text: "echo: hello" }],
        success: true,
      }),
    ).not.toBe(true);
  });
});

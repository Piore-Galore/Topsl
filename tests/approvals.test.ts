// Generated by Codex CLI 0.163.0; see scripts/codex-schema-subset.mjs.
const codexSchema = JSON.parse(
  readFileSync(
    path.resolve("tests/fixtures/codex-app-server-0.163.0.schema.json"),
    "utf8",
  ),
);
function codexAccepts(definition: string, value: unknown) {
  const result = z
    .fromJSONSchema({
      ...codexSchema,
      $ref: `#/definitions/${definition.replaceAll("/", "~1")}`,
    })
    .safeParse(value);
  return result.success
    ? true
    : `${definition}: ${JSON.stringify(result.error.issues)}`;
}
/** How `visible` writes a character it will not show as itself. */
const escaped = (codePoint: number) =>
  `${String.fromCharCode(92)}u{${codePoint.toString(16)}}`;
const base = {
  threadId: "thread",
  turnId: "turn",
  itemId: "item",
  startedAtMs: 1_760_600_000_000,
};
const approval = (
  summary: ApprovalSummary | undefined,
  request: unknown = {},
): Approval => ({
  id: "approval",
  runId: "run",
  method: "item/commandExecution/requestApproval",
  description: JSON.stringify(request, null, 2),
  ...(summary ? { summary } : {}),
  digest: "digest",
  requestId: 7,
  createdAt: "2026-10-16T00:00:00.000Z",
});
const card = (value: Approval) =>
  renderToStaticMarkup(
    createElement(ApprovalCard, { approval: value, decide: () => {} }),
  );
/** Asserts that `parts` appear in `text` in this order. */
function inOrder(text: string, parts: string[]) {
  let from = 0;
  for (const part of parts) {
    const at = text.indexOf(part, from);
    expect(at, part).toBeGreaterThanOrEqual(0);
    from = at + part.length;
  }
}

describe("approval summaries", () => {
  test("a command request names the command, its folder and what allowing does", () => {
    const request = {
      ...base,
      command: "npm test",
      cwd: "/work/project",
    };
    expect(codexAccepts("CommandExecutionRequestApprovalParams", request)).toBe(
      true,
    );
    expect(commandApprovalSummary(request)).toEqual({
      title: "Run a command",
      details: [
        { label: "Command", value: "npm test" },
        { label: "Folder", value: "/work/project" },
      ],
      effects: ["Allowing lets Codex run this command once.", sandboxNote],
    });
    expect(sandboxNote).toContain("may run with your own access");
    expect(sandboxNote).toContain("once, in a live qualification");
    expect(sandboxNote).toContain("documentation does not confirm it");
    expect(commandApprovalSummary(base).details[0]).toEqual({
      label: "Command",
      value: "Codex did not report the command.",
    });
  });

  test("network access, extra permissions, proposed rules and input are spelled out", () => {
    const request = {
      ...base,
      command: "npm install",
      cwd: "/work/project",
      reason: "Needs the package registry.",
      networkApprovalContext: { host: "registry.npmjs.org", protocol: "https" },
      additionalPermissions: {
        fileSystem: {
          entries: [
            { access: "write", path: { type: "path", path: "/work/cache" } },
            {
              access: "read",
              path: { type: "special", value: { kind: "root" } },
            },
            {
              access: "deny",
              path: { type: "glob_pattern", pattern: "**/.env" },
            },
          ],
          write: ["/work/legacy"],
        },
        network: { enabled: true },
      },
      proposedExecpolicyAmendment: ["npm", "install"],
    };
    expect(codexAccepts("CommandExecutionRequestApprovalParams", request)).toBe(
      true,
    );
    expect(commandApprovalSummary(request)).toEqual({
      title: "Run a command",
      details: [
        { label: "Command", value: "npm install" },
        { label: "Folder", value: "/work/project" },
        { label: "Network", value: "registry.npmjs.org (https)" },
        {
          label: "Extra permissions",
          value: [
            "Write /work/cache",
            "Read the whole file system",
            "No access to files matching **/.env",
            "Write /work/legacy",
            "Network access",
          ].join("\n"),
        },
        { label: "Codex's reason", value: "Needs the package registry." },
      ],
      effects: [
        "Allowing lets Codex run this command once.",
        "Allowing also gives it the extra permissions listed above.",
        sandboxNote,
        "Codex also proposed a lasting rule for similar requests. Allowing once does not add it.",
      ],
    });
    const input = { ...base, kind: "writeStdin", command: "yes" };
    expect(codexAccepts("CommandExecutionRequestApprovalParams", input)).toBe(
      true,
    );
    expect(commandApprovalSummary(input)).toMatchObject({
      title: "Send input to a running command",
      effects: ["Allowing lets Codex send this input once."],
    });
  });

  test("a file change lists the files from its item and the folder grantRoot asks for", () => {
    const request = {
        ...base,
        reason: "Writes the build output.",
        grantRoot: "/work",
      },
      item = {
        type: "fileChange",
        id: "item",
        status: "inProgress",
        changes: [
          {
            path: "/work/project/notes.md",
            kind: { type: "update", move_path: null },
            diff: "@@ -1 +1 @@\n-old\n+new\n",
          },
          {
            path: "/work/project/src/new.ts",
            kind: { type: "add" },
            diff: "export {};\n",
          },
          { path: "/work/project/old.ts", kind: { type: "delete" }, diff: "" },
          {
            path: "/work/project/a.ts",
            kind: { type: "update", move_path: "/work/project/b.ts" },
            diff: "",
          },
        ],
      };
    expect(codexAccepts("FileChangeRequestApprovalParams", request)).toBe(true);
    expect(
      codexAccepts("v2/ItemStartedNotification", {
        threadId: "thread",
        turnId: "turn",
        startedAtMs: base.startedAtMs,
        item,
      }),
    ).toBe(true);
    expect(fileChangeApprovalSummary(request, item)).toEqual({
      title: "Change files",
      details: [
        {
          label: "Files",
          value: [
            "Edit /work/project/notes.md",
            "Create /work/project/src/new.ts",
            "Delete /work/project/old.ts",
            "Move /work/project/a.ts to /work/project/b.ts",
          ].join("\n"),
        },
        { label: "Write access requested", value: "/work" },
        { label: "Codex's reason", value: "Writes the build output." },
      ],
      effects: [
        "Allowing lets Codex apply this change once.",
        "Allowing also lets Codex write under /work for the rest of the session.",
      ],
    });
    // Without its item, the request does not say which files.
    expect(fileChangeApprovalSummary(base, undefined)).toEqual({
      title: "Change files",
      details: [{ label: "Files", value: "Codex did not report which files." }],
      effects: ["Allowing lets Codex apply this change once."],
    });
  });

  test("characters that could hide or reorder text are shown as escapes", () => {
    const override = String.fromCodePoint(0x202e),
      zeroWidth = String.fromCodePoint(0x200b),
      tag = String.fromCodePoint(0xe0041),
      escape = String.fromCodePoint(0x1b);
    expect(
      visible(`rm -rf ~/${override}gpj.sh${zeroWidth}${tag}\r${escape}[2K`),
    ).toBe(
      `rm -rf ~/${escaped(0x202e)}gpj.sh${escaped(0x200b)}${escaped(0xe0041)}${escaped(0xd)}${escaped(0x1b)}[2K`,
    );
    // Lines and tabs stay as they are, and long text is cut with a count.
    expect(visible("a\n\tb")).toBe("a\n\tb");
    expect(visible("x".repeat(10), 4)).toBe("xxxx… (6 more characters)");
    expect(
      commandApprovalSummary({ ...base, command: `echo ${override}hi` })
        .details[0].value,
    ).toBe(`echo ${escaped(0x202e)}hi`);
  });

  test("a name or folder cannot add a line of its own, while a command keeps its lines", () => {
    const fake = "\nDelete /work/project/keep.md",
      command = commandApprovalSummary({
        ...base,
        command: "cat <<EOF\nhello\nEOF",
        cwd: `/work${fake}`,
        additionalPermissions: {
          fileSystem: { write: [`/work/cache${fake}`] },
        },
      }),
      change = fileChangeApprovalSummary(
        { ...base, grantRoot: `/work${fake}` },
        {
          changes: [
            { path: `/work/a.md${fake}`, kind: { type: "update" } },
            {
              path: "/work/b.md",
              kind: { type: "update", move_path: `/work/c.md${fake}` },
            },
          ],
        },
      ),
      escapedFake = `${escaped(0xa)}Delete /work/project/keep.md`;
    expect(command.details).toEqual([
      { label: "Command", value: "cat <<EOF\nhello\nEOF" },
      { label: "Folder", value: `/work${escapedFake}` },
      { label: "Extra permissions", value: `Write /work/cache${escapedFake}` },
    ]);
    expect(change.details.slice(0, 2)).toEqual([
      {
        label: "Files",
        value: `Edit /work/a.md${escapedFake}\nMove /work/b.md to /work/c.md${escapedFake}`,
      },
      { label: "Write access requested", value: `/work${escapedFake}` },
    ]);
    expect(change.effects[1]).toBe(
      `Allowing also lets Codex write under /work${escapedFake} for the rest of the session.`,
    );
    expect(visible("a\tb", 10, false)).toBe(`a${escaped(0x9)}b`);
  });

  test("Codex's started change is kept as its files and the digests of their diffs", () => {
    const adapter = new CodexAdapter(),
      change = {
        path: "/work/notes.md",
        kind: { type: "update", move_path: null },
        diff: "@@ -1 +1 @@\n-old\n+new\n",
      };
    expect(
      adapter.startedItem("item/started", {
        threadId: "thread",
        turnId: "turn",
        startedAtMs: base.startedAtMs,
        item: {
          type: "fileChange",
          id: "change",
          status: "inProgress",
          changes: [change],
        },
      }),
    ).toEqual({
      threadId: "thread",
      turnId: "turn",
      id: "change",
      item: {
        type: "fileChange",
        id: "change",
        changes: [
          {
            path: change.path,
            kind: change.kind,
            diffDigest: hash(change.diff),
          },
        ],
      },
    });
    // Other items, and other notifications, are not kept.
    expect(
      adapter.startedItem("item/started", {
        threadId: "thread",
        turnId: "turn",
        startedAtMs: base.startedAtMs,
        item: { type: "commandExecution", id: "command" },
      }),
    ).toBeNull();
    expect(
      adapter.startedItem("item/completed", {
        threadId: "thread",
        turnId: "turn",
        item: { type: "fileChange", id: "change", changes: [] },
      }),
    ).toBeNull();
  });
});

describe("approval card", () => {
  test("says what allowing does before the request's JSON, with Deny first", () => {
    const request = {
        ...base,
        command: 'echo "<img src=x onerror=alert(1)>"',
        cwd: "/work/project",
      },
      html = card(approval(commandApprovalSummary(request), request));
    inOrder(html, [
      "Run a command",
      "Command",
      "echo &quot;&lt;img src=x onerror=alert(1)&gt;&quot;",
      "Folder",
      "/work/project",
      "Allowing lets Codex run this command once.",
      "may run with your own access",
      "<details>",
      "Request as sent",
      "&quot;cwd&quot;: &quot;/work/project&quot;",
      "</details>",
      ">Deny<",
      ">Review &amp; allow once<",
    ]);
    expect(html).not.toContain("<img");
  });

  test("a file change card names its files and grantRoot's folder", () => {
    const html = card(
      approval(
        fileChangeApprovalSummary(
          { ...base, grantRoot: "/work" },
          {
            type: "fileChange",
            id: "item",
            status: "inProgress",
            changes: [
              {
                path: "/work/project/notes.md",
                kind: { type: "update", move_path: null },
                diff: "",
              },
            ],
          },
        ),
      ),
    );
    inOrder(html, [
      "Change files",
      "File",
      "Edit /work/project/notes.md",
      "Write access requested",
      "/work",
      "Allowing lets Codex apply this change once.",
      "Allowing also lets Codex write under /work for the rest of the session.",
      ">Deny<",
      ">Review &amp; allow once<",
    ]);
  });

  test("an approval recorded before summaries shows its JSON as before", () => {
    const html = card(approval(undefined, { ...base, command: "npm test" }));
    inOrder(html, [
      "Native approval requested",
      "<pre>",
      "&quot;command&quot;: &quot;npm test&quot;",
      ">Deny<",
      ">Review &amp; allow once<",
    ]);
    expect(html).not.toContain("<details>");
  });

  test("Topsl's confirmation repeats the summary with the request's identifiers", () => {
    const summary = commandApprovalSummary({
      ...base,
      command: "npm test",
      cwd: "/work/project",
    });
    expect(approvalConfirmation(approval(summary))).toBe(
      [
        "Run a command",
        "",
        "Command: npm test",
        "Folder: /work/project",
        "",
        "Allowing lets Codex run this command once.",
        sandboxNote,
        "",
        "Run: run",
        "Request: 7",
        "Digest: digest",
      ].join("\n"),
    );
    // A value on several lines starts on its own line, indented, so none of
    // its lines reads as Topsl's own.
    expect(
      approvalText(
        approval(
          fileChangeApprovalSummary(base, {
            changes: [
              { path: "/a", kind: { type: "add" } },
              { path: "/b", kind: { type: "delete" } },
            ],
          }),
        ),
      ),
    ).toContain("Files:\n    Create /a\n    Delete /b\n\nAllowing");
    expect(
      approvalText(
        approval(
          commandApprovalSummary({
            ...base,
            command: "echo one\nAllowing lets Codex run nothing.",
          }),
        ),
      ),
    ).toContain(
      "Command:\n    echo one\n    Allowing lets Codex run nothing.\n\nAllowing lets Codex run this command once.",
    );
    const legacy = approval(undefined, { command: "npm test" });
    expect(approvalConfirmation(legacy)).toBe(
      `${legacy.description}\n\nRun: run\nRequest: 7\nDigest: digest`,
    );
  });
});

describe("approvals from the Codex stand-in", () => {
  const cleanup: Array<() => Promise<void>> = [];
  afterEach(async () => {
    for (const step of cleanup.splice(0).reverse()) await step();
  });
  async function setup() {
    const f = await fixture(),
      log = path.join(f.directory, "frames.jsonl"),
      runtime = new RuntimeManager(
        f.store,
        () => {},
        () => {},
        (_executable, cwd) =>
          new RpcPeer(
            process.execPath,
            [path.resolve("tests/fixtures/codex.cjs")],
            cwd,
            {
              ...nativeEnvironment(),
              ELECTRON_RUN_AS_NODE: "1",
              FIXTURE_LOG: log,
            },
          ),
      );
    cleanup.push(async () => {
      await runtime.close();
      f.store.close();
      await rm(f.directory, { recursive: true, force: true });
    });
    const project = {
        id: "p",
        name: "fixture",
        path: f.directory,
        realPath: f.directory,
        trusted: true,
        createdAt: now(),
      },
      conversation = {
        id: "c",
        projectId: "p",
        title: "Fixture chat",
        nativeSessions: {},
        createdAt: now(),
      };
    f.store.put("project", project);
    f.store.put("conversation", conversation);
    /** Starts an editing chat turn and waits for its one approval. */
    const ask = async (prompt: string) => {
      const run = await runtime.start(
        f.installation,
        conversation,
        project,
        prompt,
        "fixture-model",
        "edit",
      );
      await vi.waitFor(() =>
        expect(
          f.store.list<Approval>("approval").filter((a) => a.runId === run.id),
        ).toHaveLength(1),
      );
      return {
        run,
        approval: f.store
          .list<Approval>("approval")
          .find((a) => a.runId === run.id)!,
      };
    };
    /** Decides, then waits for the run to end and Topsl to free the project. */
    const decide = async (run: Run, value: Approval, allow: boolean) => {
      runtime.decide(value.id, value.digest, allow);
      await vi.waitFor(() =>
        expect(f.store.get<Run>("run", run.id)?.status).toBe("completed"),
      );
      await vi.waitFor(() => expect(runtime.hasActive()).toBe(false), {
        timeout: 30_000,
      });
    };
    const frames = () =>
      readFileSync(log, "utf8")
        .trim()
        .split("\n")
        .map((line) => JSON.parse(line) as { from: string; frame: any });
    return { ...f, runtime, ask, decide, frames };
  }

  test("each request is described from what Codex reported, and its digest binds a change's files", async () => {
    const f = await setup();
    const command = await f.ask("approval"),
      commandRequest = JSON.parse(command.approval.description);
    expect(command.approval.summary).toEqual({
      title: "Run a command",
      details: [
        { label: "Command", value: "fixture read command" },
        { label: "Folder", value: commandRequest.cwd },
      ],
      effects: ["Allowing lets Codex run this command once.", sandboxNote],
    });
    await f.decide(command.run, command.approval, false);

    const change = await f.ask("file approval"),
      changeRequest = JSON.parse(change.approval.description),
      files = change.approval.summary!.details[0].value.split("\n");
    expect(change.approval.summary).toEqual({
      title: "Change files",
      details: [
        { label: "Files", value: files.join("\n") },
        { label: "Write access requested", value: changeRequest.grantRoot },
        {
          label: "Codex's reason",
          value: "Fixture asks to write outside the project.",
        },
      ],
      effects: [
        "Allowing lets Codex apply this change once.",
        `Allowing also lets Codex write under ${changeRequest.grantRoot} for the rest of the session.`,
      ],
    });
    // The stand-in works in a folder inside grantRoot's.
    const cwd = path.dirname(files[0].slice("Edit ".length));
    expect(path.dirname(cwd)).toBe(changeRequest.grantRoot);
    expect(files).toEqual([
      `Edit ${path.join(cwd, "notes.md")}`,
      `Create ${path.join(cwd, "src", "added.ts")}`,
    ]);
    // The change as the stand-in started it, kept with its diffs' digests.
    const item = {
        type: "fileChange",
        id: "change-fixture",
        changes: [
          {
            path: path.join(cwd, "notes.md"),
            kind: { type: "update", move_path: null },
            diffDigest: hash("@@ -1 +1 @@\n-old\n+new\n"),
          },
          {
            path: path.join(cwd, "src", "added.ts"),
            kind: { type: "add" },
            diffDigest: hash("export {};\n"),
          },
        ],
      },
      digest = (subject?: unknown) =>
        hash(
          stable({
            requestId: change.approval.requestId,
            method: change.approval.method,
            params: changeRequest,
            ...(subject ? { subject } : {}),
            runId: change.run.id,
            installationRevisionId: f.installation.revisionId,
          }),
        );
    expect(change.approval.digest).toBe(digest(item));
    expect(change.approval.digest).not.toBe(digest());
    await f.decide(change.run, change.approval, true);

    // Codex's answers reached the stand-in, and every approval frame on
    // both sides follows the schema Codex 0.163.0 generates.
    const frames = f.frames(),
      replies = frames.filter(
        (entry) =>
          entry.from === "topsl" && entry.frame.id === "approval-fixture",
      );
    expect(replies.map((entry) => entry.frame.result)).toEqual([
      { decision: "decline" },
      { decision: "accept" },
    ]);
    expect(
      codexAccepts(
        "CommandExecutionRequestApprovalResponse",
        replies[0].frame.result,
      ),
    ).toBe(true);
    expect(
      codexAccepts(
        "FileChangeRequestApprovalResponse",
        replies[1].frame.result,
      ),
    ).toBe(true);
    const sent = (method: string) =>
      frames.find(
        (entry) => entry.from === "fixture" && entry.frame.method === method,
      )!.frame.params;
    expect(
      codexAccepts(
        "CommandExecutionRequestApprovalParams",
        sent("item/commandExecution/requestApproval"),
      ),
    ).toBe(true);
    expect(
      codexAccepts(
        "FileChangeRequestApprovalParams",
        sent("item/fileChange/requestApproval"),
      ),
    ).toBe(true);
    expect(
      codexAccepts("v2/ItemStartedNotification", sent("item/started")),
    ).toBe(true);
  });
});

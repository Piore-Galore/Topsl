/** A runtime manager with the chat stand-in injected, as the runtime tests
 * use it. An injected stand-in is an isolated fixture: nothing qualifies it. */
async function injected(env: Record<string, string> = {}) {
  const f = await fixture(),
    log = path.join(f.directory, "frames.jsonl");
  const runtime = new RuntimeManager(
    f.store,
    () => {},
    () => {},
    (_executable, cwd) =>
      new RpcPeer(
        process.execPath,
        [path.resolve("tests/fixtures/codex.cjs")],
        cwd,
        {
          ...nativeEnvironment(),
          ELECTRON_RUN_AS_NODE: "1",
          FIXTURE_LOG: log,
          ...env,
        },
      ),
  );
  cleanup.push(async () => {
    await runtime.close();
    f.store.close();
    await rm(f.directory, { recursive: true, force: true });
  });
  f.store.put("project", project(f.directory));
  f.store.put("conversation", conversation());
  const start = (presetId: ChatPresetId, prompt = "hello", chat = "c") => {
    const preset = chatPreset(presetId);
    return runtime.start(
      f.installation,
      f.store.get<any>("conversation", chat),
      f.store.get<any>("project", "p"),
      prompt,
      "fixture-model",
      preset.mode,
      undefined,
      preset.approvalPolicy,
    );
  };
  const finished = async (id: string) => {
    await vi.waitFor(
      () =>
        expect(["completed", "failed"]).toContain(
          f.store.get<Run>("run", id)?.status,
        ),
      settled,
    );
    // The workspace stays leased until Topsl confirms the process exited,
    // which can take seconds on Windows. The next run needs it free.
    await vi.waitFor(() => expect(runtime.hasActive()).toBe(false), {
      timeout: 30_000,
    });
  };
  return { ...f, runtime, start, finished, frames: () => readFrames(log) };
}

/** Qualifications refuse the temporary directory, where the fixture's own
 * folder lives, so each gets a folder under the repository's cache. */
async function qualificationParent() {
  const cache = path.resolve("node_modules/.cache");
  await mkdir(cache, { recursive: true });
  const parent = await mkdtemp(path.join(cache, "topsl-qualify-"));
  cleanup.push(() => rm(parent, { recursive: true, force: true }));
  return parent;
}
/**
 * The qualification stand-in as a launched executable, so the manager uses
 * its production route and reads the qualification Topsl recorded. Without
 * changing the executable, writing `broken` to `sandboxFlag` makes its sandbox
 * let every write through, and writing an id to `accountFlag` makes it report
 * another ChatGPT account.
 */
async function launched(env: Record<string, string> = {}) {
  const f = await fixture(),
    log = path.join(f.directory, "frames.jsonl"),
    sandboxFlag = path.join(f.directory, "sandbox-flag"),
    accountFlag = path.join(f.directory, "account-flag"),
    workspace = path.join(f.directory, "workspace");
  await mkdir(workspace);
  const read = (file: string) => `"$(cat ${JSON.stringify(file)} 2>/dev/null)"`,
    variables = Object.entries({ FIXTURE_LOG: log, ...env })
      .map(([name, value]) => `${name}=${JSON.stringify(value)} `)
      .join("");
  await writeFile(
    f.installation.path,
    `#!/bin/sh\nFIXTURE_SANDBOX=${read(sandboxFlag)} FIXTURE_ACCOUNT_ID=${read(accountFlag)} ${variables}ELECTRON_RUN_AS_NODE=1 exec ${JSON.stringify(process.execPath)} ${JSON.stringify(path.resolve("tests/fixtures/codex-qualify.cjs"))}\n`,
  );
  await chmod(f.installation.path, 0o700);
  const installation: Installation = {
    ...f.installation,
    ...(await identity(f.installation.path)),
  };
  f.store.put("installation", installation);
  f.store.put("runtime-model-catalog", {
    id: installation.id,
    runtimeRevision: installation.revisionId,
    executableIdentity: installation.identity,
    models: [
      {
        id: "fixture",
        model: "fixture-model",
        name: "Fixture",
        description: "",
        isDefault: true,
        supportedReasoningEfforts: [],
      },
    ],
    observedAt: now(),
  });
  const runtime = new RuntimeManager(
    f.store,
    () => {},
    () => {},
  );
  cleanup.push(async () => {
    await runtime.close();
    f.store.close();
    await rm(f.directory, { recursive: true, force: true });
  });
  f.store.put("project", project(workspace));
  f.store.put("conversation", conversation());
  const qualify = async () =>
    runtime.qualify(
      installation,
      { model: "fixture-model" },
      await qualificationParent(),
    );
  const startNever = (prompt = "hello") =>
    runtime.start(
      installation,
      f.store.get<any>("conversation", "c"),
      f.store.get<any>("project", "p"),
      prompt,
      "fixture-model",
      "edit",
      undefined,
      "never",
    );
  return {
    ...f,
    installation,
    runtime,
    workspace,
    sandboxFlag,
    accountFlag,
    qualify,
    startNever,
    blocks: () => runtime.chatPresetBlocks(installation),
    frames: () => readFrames(log),
  };
}


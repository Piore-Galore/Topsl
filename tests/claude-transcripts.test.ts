import os from "node:os";
import path from "node:path";
import {
  mkdir,
  mkdtemp,
  realpath,
  rm,
  symlink,
  truncate,
  utimes,
  writeFile,
} from "node:fs/promises";
import { afterEach, describe, expect, test } from "vitest";
import { hash, uid } from "../packages/domain/invariants";
import {
  claudeTranscriptShapes,
  maxTranscriptBytes,
  readClaudeStepReply,
} from "../packages/history/claude-transcript";

/**
 * Claude Code session transcripts in the record shapes Topsl recognizes.
 * They follow what Topsl's history reader and its fixtures already read:
 * `type`, `sessionId`, `cwd`, `uuid`, `timestamp` and a `message` with a role
 * and content. The other fields and record types are inferred, not taken
 * from a real transcript; the plan's step 5 checks them in live runs.
 */
const session = "0f8d6c1e-6a2b-4c3d-9e8f-7a6b5c4d3e2f";
const directories: string[] = [];
afterEach(async () => {
  for (const directory of directories.splice(0))
    await rm(directory, { recursive: true, force: true });
});
const jsonl = (...records: unknown[]) =>
  records.map((record) => JSON.stringify(record) + "\n").join("");

/** A project folder, and Claude Code's folder for its transcripts. */
async function setup() {
  const root = await realpath(
    await mkdtemp(path.join(os.tmpdir(), "topsl-test-transcript-")),
  );
  directories.push(root);
  const folder = path.join(root, "project"),
    config = path.join(root, "claude"),
    projects = path.join(config, "projects"),
    // Claude Code names a folder's transcripts after its path.
    sessions = path.join(projects, folder.replace(/[^a-zA-Z0-9]/g, "-")),
    file = path.join(sessions, `${session}.jsonl`),
    // Topsl asked to open Claude Code a minute ago.
    openedAt = new Date(Date.now() - 60_000).toISOString();
  await mkdir(folder);
  await mkdir(sessions, { recursive: true });
  const common = (extra: Record<string, unknown> = {}) => ({
    parentUuid: null,
    isSidechain: false,
    userType: "external",
    cwd: folder,
    sessionId: session,
    version: "2.1.300",
    gitBranch: "",
    uuid: uid(),
    timestamp: new Date().toISOString(),
    ...extra,
  });
  const user = (
    content: string | unknown[],
    extra: Record<string, unknown> = {},
  ) => ({
    ...common(extra),
    type: "user",
    message: { role: "user", content },
  });
  const assistant = (
    content: unknown[],
    extra: Record<string, unknown> = {},
    id = `msg_${uid()}`,
  ) => ({
    ...common(extra),
    type: "assistant",
    requestId: `req_${uid()}`,
    message: {
      id,
      type: "message",
      role: "assistant",
      model: "fixture",
      content,
      stop_reason: null,
      stop_sequence: null,
      usage: { input_tokens: 1, output_tokens: 1 },
    },
  });
  const text = (value: string) => ({ type: "text", text: value });
  /** What Claude Code records when the owner types /exit. */
  const exit = () => [
    user(
      "Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.",
      { isMeta: true },
    ),
    user(
      "<command-name>/exit</command-name>\n            <command-message>exit</command-message>\n            <command-args></command-args>",
    ),
    user("<local-command-stdout>Goodbye!</local-command-stdout>"),
  ];
  /** A build session: the instructions, a tool call, and Claude's reply. */
  const build = (reply = "Changed the value to two in file.ts.") => {
    const tool = `toolu_${uid()}`,
      first = `msg_${uid()}`;
    return [
      {
        type: "file-history-snapshot",
        messageId: uid(),
        snapshot: { messageId: uid(), trackedFileBackups: {}, timestamp: "" },
        isSnapshotUpdate: false,
      },
      user("Role: builder\nObjective: value two"),
      // One message's parts are consecutive records with its id.
      assistant(
        [{ type: "thinking", thinking: "Read the file.", signature: "s" }],
        {},
        first,
      ),
      assistant([text("I'll change the value.")], {}, first),
      assistant(
        [
          {
            type: "tool_use",
            id: tool,
            name: "Edit",
            input: { file_path: path.join(folder, "file.ts") },
          },
        ],
        {},
        first,
      ),
      user(
        [
          {
            type: "tool_result",
            tool_use_id: tool,
            content: "The file has been updated.",
          },
        ],
        { toolUseResult: { filePath: path.join(folder, "file.ts") } },
      ),
      assistant([text(reply)]),
      {
        ...common(),
        type: "system",
        subtype: "informational",
        content: "Turn finished.",
        level: "info",
        isMeta: false,
      },
      ...exit(),
      { type: "summary", summary: "Change the value", leafUuid: uid() },
    ];
  };
  return {
    folder,
    config,
    projects,
    sessions,
    file,
    openedAt,
    user,
    assistant,
    text,
    exit,
    build,
    write: (...records: unknown[]) => writeFile(file, jsonl(...records)),
    read: (overrides: { folder?: string; sessionId?: string } = {}) =>
      readClaudeStepReply({
        configDirectory: config,
        sessionId: session,
        folder,
        openedAt,
        ...overrides,
      }),
  };
}
const unread = async (
  read: Promise<Awaited<ReturnType<typeof readClaudeStepReply>>>,
  reason: RegExp,
) => {
  const result = await read;
  expect(result.ok).toBe(false);
  expect(result.ok ? null : result.reason).toMatch(reason);
};

describe("Claude's reply from a step's session transcript", () => {
  test("takes Claude's last message after the last prompt, with what Topsl read", async () => {
    const f = await setup(),
      records = f.build();
    await f.write(...records);
    const result = await f.read();
    expect(result).toEqual({
      ok: true,
      text: "Changed the value to two in file.ts.",
      source: {
        shapes: claudeTranscriptShapes,
        sessionId: session,
        file: f.file,
        bytes: Buffer.byteLength(jsonl(...records)),
        sha256: hash(jsonl(...records)),
        records: records.length,
        replyRecord: (records[6] as { uuid: string }).uuid,
      },
    });
  });

  test("joins the text of the reply's parts, and skips earlier turns and a subagent's side chain", async () => {
    const f = await setup(),
      id = `msg_${uid()}`;
    await f.write(
      f.user("First question"),
      f.assistant([f.text("First answer")]),
      f.user("Second question"),
      f.assistant(
        [{ type: "thinking", thinking: "Hm.", signature: "s" }],
        {},
        id,
      ),
      f.assistant([f.text("Second answer,")], {}, id),
      f.assistant([f.text("in two parts.")], {}, id),
      f.user("A subagent's prompt", { isSidechain: true }),
      f.assistant([f.text("A subagent's answer")], { isSidechain: true }),
      ...f.exit(),
    );
    const result = await f.read();
    expect(result.ok && result.text).toBe("Second answer,\nin two parts.");
  });

  test("a review's reply comes from a transcript of its copy, and from no other folder", async () => {
    const f = await setup(),
      copy = path.join(path.dirname(f.folder), "topsl-candidate-copy");
    await mkdir(copy);
    await f.write(
      { ...f.user("Role: reviewer"), cwd: copy },
      { ...f.assistant([f.text('{"findings":[]}')]), cwd: copy },
    );
    const result = await f.read({ folder: copy });
    expect(result.ok && result.text).toBe('{"findings":[]}');
    await unread(
      f.read(),
      /Line 1 of the transcript names a folder outside the step's\./,
    );
  });

  test("a record in a folder inside the step's, as after Claude changes into it, still counts", async () => {
    const f = await setup(),
      inside = path.join(f.folder, "packages", "app"),
      // A sibling whose name starts with the folder's is outside it.
      beside = f.folder + "-other";
    await mkdir(inside, { recursive: true });
    await mkdir(beside);
    await f.write(f.user("Role: builder"), {
      ...f.assistant([f.text("Built it.")]),
      cwd: inside,
    });
    const result = await f.read();
    expect(result.ok && result.text).toBe("Built it.");
    await f.write(f.user("Role: builder"), {
      ...f.assistant([f.text("Built it.")]),
      cwd: beside,
    });
    await unread(
      f.read(),
      /Line 2 of the transcript names a folder outside the step's\./,
    );
  });

  test("a missing transcript, or none for this session, falls back to paste", async () => {
    const f = await setup();
    await unread(
      f.read(),
      /Claude Code has no transcript for session 0f8d6c1e-.* in /,
    );
    await unread(
      readClaudeStepReply({
        configDirectory: path.join(f.config, "elsewhere"),
        sessionId: session,
        folder: f.folder,
        openedAt: f.openedAt,
      }),
      /Claude Code has no projects folder Topsl can read at /,
    );
    await f.write(...f.build());
    // Only a session id Topsl generated names a file.
    await unread(
      f.read({ sessionId: "../" + session }),
      /The step's session id is not one Topsl generated\./,
    );
    // Two project folders with the session's transcript are ambiguous.
    const other = path.join(f.projects, "another-folder");
    await mkdir(other);
    await writeFile(path.join(other, `${session}.jsonl`), jsonl(...f.build()));
    await unread(f.read(), /More than one of Claude Code's project folders/);
  });

  test("a record of another session or folder, or one naming neither, falls back to paste", async () => {
    const f = await setup(),
      records = f.build();
    await f.write(...records.slice(0, 3), { ...records[3], sessionId: uid() });
    await unread(f.read(), /Line 4 of the transcript names another session\./);
    await f.write(...records.slice(0, 2), { ...records[2], cwd: os.tmpdir() });
    await unread(
      f.read(),
      /Line 3 of the transcript names a folder outside the step's\./,
    );
    const { sessionId: _session, ...unnamed } = records[1] as Record<
      string,
      unknown
    >;
    await f.write(records[0], unnamed);
    await unread(f.read(), /Line 2 of the transcript names no session\./);
    const { cwd: _cwd, ...nowhere } = records[1] as Record<string, unknown>;
    await f.write(records[0], nowhere);
    await unread(f.read(), /Line 2 of the transcript names no folder\./);
    // A record that carries no conversation must not name another session either.
    await f.write({ ...records[0], sessionId: uid() }, ...records.slice(1));
    await unread(f.read(), /Line 1 of the transcript names another session\./);
  });

  test("a record Topsl does not recognize falls back to paste", async () => {
    const f = await setup(),
      records = f.build();
    for (const [record, reason] of [
      [
        { type: "queue-operation", operation: "enqueue", sessionId: session },
        /Line 2 of the transcript has the record type "queue-operation", which Topsl does not recognize\./,
      ],
      [
        f.assistant([{ type: "server_tool_use", id: "s", name: "web_search" }]),
        /Line 2 of the transcript has a message part of type "server_tool_use", which Topsl does not recognize\./,
      ],
      [
        f.assistant([f.text("An answer")], { isFutureFlag: true }),
        /Line 2 of the transcript sets isFutureFlag, a flag Topsl does not recognize\./,
      ],
      [
        { ...f.user("A prompt"), message: { role: "assistant", content: "x" } },
        /Line 2 of the transcript has no user message\./,
      ],
      [
        { ...f.assistant([]), message: { role: "assistant", content: "x" } },
        /Line 2 of the transcript has message content Topsl does not recognize\./,
      ],
      [
        { ...f.user("A prompt"), uuid: undefined },
        /Line 2 of the transcript has no record id\./,
      ],
      [{ sessionId: session }, /Line 2 of the transcript has no record type\./],
    ] as const) {
      await f.write(records[0], record, ...records.slice(1));
      await unread(f.read(), reason);
    }
    await writeFile(f.file, jsonl(...records.slice(0, 2)) + "{not json}\n");
    await unread(f.read(), /Line 3 of the transcript is not a JSON record\./);
    await writeFile(f.file, jsonl(...records.slice(0, 2)) + "[1]\n");
    await unread(f.read(), /Line 3 of the transcript is not a JSON object\./);
    await writeFile(f.file, jsonl(...records).slice(0, -1));
    await unread(
      f.read(),
      /The session's transcript ends in the middle of a record\./,
    );
    await writeFile(f.file, "");
    await unread(f.read(), /The session's transcript is empty\./);
    await writeFile(f.file, Buffer.from([0xff, 0x0a]));
    await unread(f.read(), /The session's transcript is not valid UTF-8\./);
    await writeFile(f.file, "");
    await truncate(f.file, maxTranscriptBytes + 1);
    await unread(f.read(), /larger than the 30 MB Topsl reads\./);
  });

  test("a turn that did not end in Claude's reply falls back to paste", async () => {
    const f = await setup(),
      records = f.build(),
      prompt = f.user("Role: builder");
    const tool = f.assistant([
      { type: "tool_use", id: "toolu_1", name: "Bash", input: {} },
    ]);
    for (const [turn, reason] of [
      [
        [prompt],
        /Claude has no reply after your last prompt in this session\./,
      ],
      [
        [
          prompt,
          f.assistant([f.text("Answer")]),
          f.user("One more thing"),
          ...f.exit(),
        ],
        /Claude has no reply after your last prompt in this session\./,
      ],
      [[prompt, tool, ...f.exit()], /ended in a tool call/],
      [
        [
          prompt,
          f.assistant([f.text("Half an answ")]),
          f.user([{ type: "text", text: "[Request interrupted by user]" }]),
        ],
        /Claude's last reply in this session was interrupted\./,
      ],
      [
        [
          prompt,
          f.assistant([f.text("API Error: 403 forbidden")], {
            isApiErrorMessage: true,
          }),
        ],
        /Claude Code's last message in this session is an API error/,
      ],
      [
        [
          prompt,
          f.assistant([{ type: "thinking", thinking: "x", signature: "s" }]),
        ],
        /Claude's last message in this session has no text\./,
      ],
      [[...f.exit()], /The session has no prompt from you\./],
    ] as const) {
      await f.write(records[0], ...turn);
      await unread(f.read(), reason);
    }
  });

  test("another session written in the folder while the step was open falls back to paste, as after /clear or /branch", async () => {
    const f = await setup();
    await f.write(...f.build());
    const other = path.join(f.sessions, `${uid()}.jsonl`);
    await writeFile(other, jsonl(f.user("After /clear")));
    await unread(
      f.read(),
      /Claude Code also wrote another session's transcript for this folder while the step was open, as it does after \/clear or \/branch/,
    );
    // One written before Topsl opened this session is an earlier session.
    const before = new Date(Date.parse(f.openedAt) - 60_000);
    await utimes(other, before, before);
    expect((await f.read()).ok).toBe(true);
  });

  test.skipIf(process.platform === "win32")(
    "a transcript that is a symbolic link falls back to paste",
    async () => {
      const f = await setup(),
        target = path.join(path.dirname(f.folder), "elsewhere.jsonl");
      await writeFile(target, jsonl(...f.build()));
      await symlink(target, f.file);
      await unread(
        f.read(),
        /Topsl could not open the session's transcript as a regular file\./,
      );
    },
  );
});

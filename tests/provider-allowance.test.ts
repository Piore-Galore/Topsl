describe("owner-set budgets", () => {
  const at = new Date(2026, 9, 21, 15, 0); // Wednesday 21 October 2026, local time
  const run = (id: string, overrides: Partial<Run> = {}): Run =>
    ({
      id,
      provider: "codex",
      mode: "review",
      createdAt: new Date(2026, 9, 20, 9).toISOString(),
      ...overrides,
    }) as Run;
  const usage = (runId: string, input: number, output: number): UsageFact => ({
    id: `${runId}:turn`,
    runId,
    provider: "codex",
    input,
    output,
    cached: 0,
    source: "native-runtime",
    scope: "turn",
    semantics: "cumulative",
    scopeLevel: "turn",
    cachedIncludedInInput: true,
  });
  const budget = (overrides: Partial<ProviderBudget> = {}): ProviderBudget => ({
    id: "provider-budget:codex",
    provider: "codex",
    tokens: 1000,
    period: "week",
    updatedAt: now(),
    ...overrides,
  });
  test("periods start at local midnight, Monday and the first of the month", () => {
    expect(budgetPeriodStart("day", at)).toEqual(new Date(2026, 9, 21));
    expect(budgetPeriodStart("week", at)).toEqual(new Date(2026, 9, 19));
    expect(budgetPeriodStart("week", new Date(2026, 9, 25, 23))).toEqual(
      new Date(2026, 9, 19),
    );
    expect(budgetPeriodStart("month", at)).toEqual(new Date(2026, 9, 1));
  });
  test("remaining counts this period's known tokens of the provider's own runs", () => {
    const runs = [
      run("in"),
      run("earlier", { createdAt: new Date(2026, 9, 18).toISOString() }),
      run("claude", { provider: "claude" }),
      // A native sign-in is not model work.
      run("login", { mode: "native" }),
    ];
    const status = providerBudgetStatus(
      budget(),
      runs,
      [
        usage("in", 300, 100),
        usage("earlier", 5000, 5000),
        usage("claude", 9, 9),
      ],
      at,
    );
    expect(status).toMatchObject({
      observedTokens: 400,
      remaining: 600,
      complete: true,
      coveredRuns: 1,
      totalRuns: 1,
    });
    expect(budgetReadout(status)).toBe(
      "Owner-set budget: 1,000 tokens this week. Topsl observed 400 known tokens · 600 tokens left · 1 run reported usage.",
    );
  });
  test("a run that reported no usage makes the remainder an upper bound", () => {
    const status = providerBudgetStatus(
      budget(),
      [
        run("in"),
        run("terminal", { mode: "native", permissionMode: "provider-default" }),
      ],
      [usage("in", 300, 100)],
      at,
    );
    expect(status).toMatchObject({
      remaining: 600,
      complete: false,
      coveredRuns: 1,
      totalRuns: 2,
    });
    expect(budgetReadout(status)).toContain(
      "at most 600 tokens left · 1 of 2 runs reported no usage",
    );
  });
  test("going over shows the overage, not a negative remainder", () => {
    const status = providerBudgetStatus(
      budget({ tokens: 100 }),
      [run("in")],
      [usage("in", 300, 100)],
      at,
    );
    expect(status.remaining).toBe(-300);
    expect(budgetReadout(status)).toContain("over by 300 tokens");
  });
});


// Generated by Codex CLI 0.163.0; see scripts/codex-schema-subset.mjs.
const codexSchema = JSON.parse(
  readFileSync(
    path.resolve("tests/fixtures/codex-app-server-0.163.0.schema.json"),
    "utf8",
  ),
);
function codexAccepts(definition: string, value: unknown) {
  const result = z
    .fromJSONSchema({
      ...codexSchema,
      $ref: `#/definitions/${definition.replaceAll("/", "~1")}`,
    })
    .safeParse(value);
  return result.success
    ? true
    : `${definition}: ${JSON.stringify(result.error.issues)}`;
}

